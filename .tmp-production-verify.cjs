const { chromium, expect } = require('@playwright/test');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const response=await page.goto('https://www.me-ish.art/natori/portfolio',{waitUntil:'networkidle',timeout:60000});
  if(response.status()!==200)throw Error('Unexpected status: '+response.status());
  await expect(page.locator('h1')).toHaveText('ナトリのあとりえ');
  const nav=page.getByRole('navigation',{name:'メインナビゲーション（モバイル）'});
  await expect(nav.getByRole('link')).toHaveText(['作品','料金','流れ','相談']);
  await expect(page.locator('#hero')).toContainText('納期の目安');
  await expect(page.locator('#portfolio-gallery-results > div')).toHaveCount(6);
  await nav.getByRole('link',{name:'作品',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('#gallery img')].every(image=>image.complete&&image.naturalWidth>0));
  await page.screenshot({path:'docs/artifacts/natori-portfolio-ux/production-mobile.png'});
  await page.getByRole('button',{name:'全9作品を見る'}).click();
  await expect(page.locator('#portfolio-gallery-results > div')).toHaveCount(9);
  await page.getByRole('button',{name:'SDキャラ',exact:true}).click();
  await expect(page.locator('#portfolio-gallery-results > div')).toHaveCount(2);
  await page.getByRole('button',{name:'すべて',exact:true}).click();
  const card=page.getByRole('button',{name:'水鏡ステラ様 を拡大表示'});
  await card.click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(card).toBeFocused();
  await nav.getByRole('link',{name:'相談',exact:true}).click();
  await expect(page.locator('#form h2')).toBeInViewport();
  await expect(page.locator('#pf-message')).toBeVisible();
  const optional=page.locator('#form details').filter({has:page.locator('summary').filter({hasText:'詳しい条件を追加する'})}).first();
  await expect(optional).not.toHaveAttribute('open','');
  await page.locator('#pricing').getByRole('link',{name:'このプランで相談'}).first().click();
  await expect(optional).toHaveAttribute('open','');
  await expect(page.getByLabel('ご依頼の種類',{exact:true})).toHaveValue('sd');
  await page.getByLabel('見積もりを希望',{exact:true}).check();
  await page.getByLabel('まず相談したい',{exact:true}).check();
  await expect(optional).not.toHaveAttribute('open','');
  const mobile=await page.evaluate(()=>({viewport:innerWidth,documentWidth:document.documentElement.scrollWidth}));
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:'docs/artifacts/natori-portfolio-ux/production-desktop.png'});
  console.log(JSON.stringify({status:response.status(),mobile,errors,checks:['gallery/filter/expand','image loading/modal/keyboard','mobile navigation','hero pricing and delivery','simplified form','plan prefill','mode switching'],formSubmitted:false}));
  if(errors.length)throw Error('Browser errors detected');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
